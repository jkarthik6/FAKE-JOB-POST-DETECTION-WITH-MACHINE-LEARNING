# Test with a sample job posting
def detect_fake_job(job_title, company_profile, description, requirements):
    text = job_title + " " + company_profile + " " + description + " " + requirements
    text_tfidf = loaded_vectorizer.transform([text])
    prediction = loaded_model.predict(text_tfidf)[0]
    return "🔹 FAKE JOB ❌" if prediction == 1 else "✅ REAL JOB ✅"

# Example usage
